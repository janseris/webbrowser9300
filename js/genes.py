#!/usr/bin/env python3
"""js/es.js -> js/mujs/jses.h (kBwEs), without comment lines and indentation: every js_State
runs it (js/mujs/jses.c). build.sh runs it."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
lines = []
for l in open(os.path.join(here, "es.js"), encoding="utf-8"):
    s = l.strip()
    if not s or s.startswith("//"): continue
    lines.append(s)
src = "\n".join(lines).encode()
def lit(b):
    out, col = '"', 0
    for c in b:
        if c == 0x5c: out += '\\\\'
        elif c == 0x22: out += '\\"'
        elif c == 0x0a: out += '\\n"\n"'
        elif 0x20 <= c < 0x7f: out += chr(c)
        else: out += '\\%03o' % c
    return out + '"'
open(os.path.join(here, "mujs/jses.h"), "w").write(
    "/* Generated by js/genprelude.py from js/es.js. Do not edit. */\nstatic const char kBwEs[] =\n" + lit(src) + ";\n")
print(len(src), "bytes")
