#!/usr/bin/env python3
"""js/es.js -> js/mujs/jses.h, without comment lines and indentation: every js_State runs the core
(kBwEs); each //@lazy NAME... block up to //@end becomes a chunk (kBwEsLazy) compiled the first
time a script reads or sets one of its NAMEs on the global object (js/mujs/jses.c). A chunk runs
as (function (G, H) {...})(this, this['%es']) with the core's helpers (its %es object) as locals.
build.sh runs it."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
core, chunks, cur = [], [], None
for l in open(os.path.join(here, "es.js"), encoding="utf-8"):
    s = l.strip()
    if s.startswith("//@lazy "): cur = (s[8:].split(), []); chunks.append(cur); continue
    if s == "//@end": cur = None; continue
    if not s or s.startswith("//"): continue
    (cur[1] if cur else core).append(s)
src = "\n".join(core)
m = re.search(r"hid\(G, '%es', \{(.*)\}\);", src)
exports = [p.split(":")[0].strip() for p in m.group(1).split(",")]
def lit(t):
    b = t.encode()
    out = '"'
    for c in b:
        if c == 0x5c: out += '\\\\'
        elif c == 0x22: out += '\\"'
        elif c == 0x0a: out += '\\n"\n"'
        elif 0x20 <= c < 0x7f: out += chr(c)
        else: out += '\\%03o' % c
    return out + '"'
o = ["/* Generated by js/genes.py from js/es.js. Do not edit. */",
     "static const char kBwEs[] =\n" + lit(src) + ";"]
pro = "(function (G, H) {\nvar " + ", ".join("%s = H.%s" % (e, e) for e in exports) + ";\n"
for i, (names, body) in enumerate(chunks):
    o.append("static const char kBwEsLazy%d[] =\n%s;" % (i, lit(pro + "\n".join(body) + "\n})(this, this['%es']);\n")))
o.append("static const BwLazyChunk kBwEsLazy[] = {")
for i, (names, body) in enumerate(chunks):
    o.append('\t{ "%s", kBwEsLazy%d, "[es %s]" },' % (" ".join(names), i, names[0]))
o.append("};")
open(os.path.join(here, "mujs/jses.h"), "w").write("\n".join(o) + "\n")
print(len(src), "bytes +", " + ".join(str(len("\n".join(b))) for n, b in chunks), "lazy")
