#!/usr/bin/env python3
"""js/prelude.js -> js/prelude.h, without comment lines and indentation: every page compiles the
eager part (kBwPrelude), so smaller is quicker on the phone. Each //@lazy [NAME...] block up to
//@end is a chunk (kBwPreludeLazy) compiled only when a page's script first reads or sets one of
its globals: the NAMEs given and the ones its top-level function and var statements declare
(except __names, its own helpers). js/bwhost.c registers them (jsB_lazy). build.sh runs it."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
core, chunks, cur = [], [], None
for l in open(os.path.join(here, "prelude.js"), encoding="utf-8"):
    s = l.strip()
    if s.startswith("//@lazy"): cur = (s[7:].split(), []); chunks.append(cur); continue
    if s == "//@end": cur = None; continue
    if cur is not None and not l[:1].isspace():
        m = re.match(r"(?:function|var)\s+([A-Za-z_$][\w$]*)", l)
        if m and not m.group(1).startswith("__") and m.group(1) not in cur[0]: cur[0].append(m.group(1))
    if not s or s.startswith("//"): continue
    (cur[1] if cur is not None else core).append(s)
def lit(t):
    b = t.encode()
    out = '"'
    for c in b:
        if c == 0x5c: out += '\\\\'
        elif c == 0x22: out += '\\"'
        elif c == 0x0a: out += '\\n"\n"'
        elif 0x20 <= c < 0x7f: out += chr(c)
        else: out += '\\%03o' % c
    return out + '"'
src = "\n".join(core)
o = ["/* Generated by js/genprelude.py from js/prelude.js. Do not edit. */",
     "static const char kBwPrelude[] =\n" + lit(src) + ";"]
for i, (names, body) in enumerate(chunks):
    o.append("static const char kBwPreludeLazy%d[] =\n%s;" % (i, lit("\n".join(body) + "\n")))
o.append("static const struct { const char *names, *src, *file; } kBwPreludeLazy[] = {")
for i, (names, body) in enumerate(chunks):
    o.append('\t{ "%s", kBwPreludeLazy%d, "[prelude %s]" },' % (" ".join(names), i, names[0]))
o.append("};")
open(os.path.join(here, "prelude.h"), "w").write("\n".join(o) + "\n")
print(len(src), "bytes +", " + ".join(str(len("\n".join(b))) for n, b in chunks), "lazy")
for n, b in chunks: print("  ", " ".join(n))
