#!/usr/bin/env python3
"""js/tests/*.js + expected.txt -> src/jstests.h: the scripts and results Tools > JavaScript test
(about:js) runs on the phone. Run it after changing a test (build.sh does)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
def lit(b):
    out = '"'
    for c in b:
        if c == 0x5c: out += '\\\\'
        elif c == 0x22: out += '\\"'
        elif c == 0x0a: out += '\\n"\n    "'
        elif 0x20 <= c < 0x7f: out += chr(c)
        else: out += '\\%03o' % c
    return out + '"'
exp = {}
for l in open(os.path.join(here, "expected.txt"), "rb"):
    n, r = l.rstrip(b"\n").split(b"\t", 1); exp[n.decode()] = r
names = sorted(f for f in os.listdir(here) if f.endswith(".js"))
o = ["// Generated by js/tests/gen.py from js/tests/*.js and expected.txt (Node's results). Do not edit.",
     "struct TJsTest { const char* iName; const char* iSource; const char* iExpect; };",
     "static const TJsTest KJsTests[] =", "    {"]
for n in names:
    src = open(os.path.join(here, n), "rb").read()
    o.append("    { %s,\n    %s,\n    %s }," % (lit(n[:-3].encode()), lit(src), lit(exp[n])))
o += ["    };", "const TInt KJsTestCount = sizeof(KJsTests) / sizeof(KJsTests[0]);", ""]
open(os.path.join(here, "..", "..", "src", "jstests.h"), "w").write("\n".join(o))
print(len(names), "tests")
